#!/usr/bin/env python3
"""Read the TV's apps, icons and inputs into app/apps.js and app/icons/.

A webOS app can't list the installed apps itself, so the menu gets them from here. tools/install.py
runs this on every install; run it alone to see the app ids for app/config.js:

    python3 tools/sync.py 192.168.1.50 --list
"""
import json
import os
import re
import shutil
import sys
import tempfile

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from tv import TV, FileServer, host_from_args  # noqa: E402

APP_DIR = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "app")


def luna(tv, uri, params="{}"):
    out = tv.check("luna-send -n 1 %s '%s'" % (uri, params), timeout=60)
    return json.loads(out[out.index("{"):])


def safe(name):
    return re.sub(r"[^A-Za-z0-9._-]", "_", name)


def launch_points(tv):
    return luna(tv, "luna://com.webos.applicationManager/listLaunchPoints").get("launchPoints", [])


def sync(tv):
    points = [p for p in launch_points(tv) if not p.get("hidden")]
    inputs = luna(tv, "luna://com.webos.service.eim/getAllInputStatus").get("devices", [])

    # The TV uploads each app's icon to us; the menu scales them when it draws.
    icon_dir = os.path.join(APP_DIR, "icons")
    shutil.rmtree(icon_dir, ignore_errors=True)
    os.makedirs(icon_dir)
    want, names = [], {}
    for p in points:
        icon = p.get("largeIcon") or p.get("icon") or ""
        ext = os.path.splitext(icon)[1].lower()
        if icon.startswith("/") and ext in (".png", ".jpg", ".jpeg"):
            names[p["id"]] = safe(p["id"]) + ext
            want.append((icon, names[p["id"]]))
    up = tempfile.mkdtemp(prefix="wii-sync-")
    try:
        with FileServer(tv, upload_dir=up) as fs:
            script = "\n".join('[ -f "%s" ] && curl -s -m 30 -T "%s" "%s/up/%s"' % (src, src, fs.url, name)
                               for src, name in want)
            tv.run(script + "\ntrue", timeout=600)
        got = set(os.listdir(up))
        for name in got:
            shutil.move(os.path.join(up, name), os.path.join(icon_dir, name))
    finally:
        shutil.rmtree(up, ignore_errors=True)

    apps = []
    for p in points:
        icon = names.get(p["id"]) if names.get(p["id"]) in got else ""
        apps.append({"id": p["id"], "title": p.get("title", p["id"]),
                     "icon": "icons/" + icon if icon else "", "iconColor": p.get("iconColor") or ""})

    # HDMI first, then the other inputs, in port order.
    inputs.sort(key=lambda d: (0 if d.get("id", "").startswith("HDMI") else 1, d.get("id", "")))
    out = {
        "apps": apps,
        "inputs": [{"appId": d["appId"], "label": d.get("label") or d["id"]} for d in inputs if d.get("appId")],
    }
    with open(os.path.join(APP_DIR, "apps.js"), "w") as f:
        f.write("// Generated by tools/sync.py: the TV's apps and inputs.\n")
        f.write("window.TV_APPS = " + json.dumps(out, indent=1, ensure_ascii=False) + ";\n")
    print("Read %d apps and %d inputs from the TV." % (len(apps), len(out["inputs"])))


def main():
    tv = TV(host_from_args(sys.argv[1:]))
    if "--list" in sys.argv:
        for p in launch_points(tv):
            print("%-40s %s%s" % (p["id"], p.get("title", ""), "  (hidden)" if p.get("hidden") else ""))
        return
    sync(tv)


if __name__ == "__main__":
    main()
